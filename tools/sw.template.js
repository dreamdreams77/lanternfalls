/* Lanternfall service worker: precaches the whole game so it installs and plays offline.
   Generated by tools/stamp_sw.py (version = hash of the cached files). */
const VERSION = '__VERSION__';
const CACHE = 'lanternfall-' + VERSION;
const ASSETS = __ASSETS__;
const INDEX = new URL('index.html', self.registration.scope).href;

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS.map(u => new Request(u, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('lanternfall-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  if (req.mode === 'navigate') {   // any page load of the app opens the cached shell, then falls back to the network
    e.respondWith(caches.match(INDEX).then(hit => hit || fetch(req)).catch(() => caches.match(INDEX)));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return res;
  }).catch(() => Response.error())));
});
